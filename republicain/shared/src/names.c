const char *republicain_observance(int ordinal, int year, int english, int utf8)
{
    unsigned i;
    for (i = 0; i < sizeof observances / sizeof observances[0]; ++i) {
        if (ordinal == (observances[i].month-1)*30 + observances[i].day-1 &&
            year >= observances[i].first_year) {
            struct name n = english && observances[i].english.plain ?
                            observances[i].english : observances[i].french;
            return utf8 && n.utf8 ? n.utf8 : n.plain;
        }
    }
    return 0;
}

